def tests(mod):
    out = []
    for v, r in TRUE:
        out.append((f"satisfies({v!r},{r!r})", lambda v=v, r=r: mod.satisfies(v, r) is True))
    for v, r in FALSE:
        out.append((f"not satisfies({v!r},{r!r})", lambda v=v, r=r: mod.satisfies(v, r) is False))
    for a, b in zip(CHAIN, CHAIN[1:]):
        out.append((f"{b} > {a}", lambda a=a, b=b: mod.satisfies(b, ">" + a) and not mod.satisfies(a, ">=" + b)))
    for v, r in [("1.2", "*"), ("a.b.c", "1.x"), ("1.2.3", ">=abc"), ("1.2.3-", "*")]:
        out.append((f"ValueError {v!r},{r!r}", lambda v=v, r=r: raises(ValueError, mod.satisfies, v, r)))
    return out


def raises(exc, fn, *a):
    try:
        fn(*a)
    except exc:
        return True
    except Exception:
        return False
    return False
